async def upload_file_handler(request):
    try:
        reader = await request.multipart()
        session_id = None
        file_data = None
        filename = None
        book_mode = False

        async for part in reader:
            if part.name == 'session_id':
                session_id = await part.text()
            elif part.name == 'book_mode':
                book_mode = (await part.text()).strip().lower() in ('1', 'true', 'yes')
            elif part.name == 'file':
                filename = part.filename
                file_data = await part.read()

        if not session_id or not file_data:
            return web.json_response(
                {'error': 'Missing session_id or file'},
                status=400
            )

        session = session_manager.get_session(session_id)
        if not session:
            return web.json_response(
                {'error': 'Invalid session_id'},
                status=404
            )

        mime_type = get_mime_type(filename)

        if mime_type == 'application/pdf':
            num_pages = check_pdf_pages(file_data)
            if num_pages > 2:
                return web.json_response(
                    {'error': f'PDF has {num_pages} pages. Maximum allowed is 2 pages. Please upload a smaller file.'},
                    status=400
                )

        if not (mime_type.startswith('image/') or mime_type == 'application/pdf'):
            return web.json_response(
                {'error': 'Unsupported file type. Use PDF or image files.'},
                status=400
            )

        base64_data = base64.b64encode(file_data).decode('utf-8')

        if book_mode:
            page_index = session_manager.add_page(session_id, base64_data, filename, mime_type)
            return web.json_response({
                'status': 'success',
                'message': f'Page {page_index + 1} ("{filename}") added to reading queue',
                'file_type': mime_type,
                'page_index': page_index,
                'total_pages': len(session['pages'])
            })

        session_manager.set_file_data(session_id, base64_data, filename, mime_type)

        return web.json_response({
            'status': 'success',
            'message': f'File "{filename}" uploaded successfully',
            'file_type': mime_type
        })

    except Exception as e:
        return web.json_response(
            {'error': f'Upload failed: {str(e)}'},
            status=500
        )

