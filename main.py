def _create_tables_sync():
    """Runs the schema SQL over a real Postgres connection (psycopg2).
    This is the part the supabase-py REST client can't do."""
    conn = psycopg2.connect(DATABASE_URL)
    try:
        conn.autocommit = True
        with conn.cursor() as cur:
            cur.execute(SCHEMA_SQL)
        logger.info("✓ Schema verified/created: users, files, urls, operations_log, chat_history")
    finally:
        conn.close()


async def init_database():
    """Call once at startup. Safe to call every time the app boots."""
    logger.info("=" * 80)
    logger.info("CREATING / VERIFYING DATABASE TABLES")
    logger.info("=" * 80)
    loop = asyncio.get_event_loop()
    try:
        await loop.run_in_executor(None, _create_tables_sync)
    except Exception as e:
        logger.critical(f"Database setup failed: {e}", exc_info=True)
        raise RuntimeError(
            "Could not create/verify tables via DATABASE_URL. Check that the "
            "connection string (including password) is correct and that your "
            "network/firewall allows outbound connections to Supabase's DB port."
        ) from e
    logger.info("=" * 80)
    logger.info("DATABASE READY")
    logger.info("=" * 80)


